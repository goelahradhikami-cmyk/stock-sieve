"""
Market Anomaly Detector - Commit 6-S.0/6-S.1.

Finds Narrative Divergence: stocks where the market's pessimistic story
(price crashing, valuation compressing) contradicts the business reality
(earnings stable, cashflow improving, balance sheet healthy).

This is NOT a factor signal. Factors measure "is this stock cheap/quality?"
Anomaly detection measures "is the market WRONG about this stock?"

Key distinction from 6-Q thesis signals:
  - 6-Q signals: earnings_acceleration, mispricing_gap → IC was NEGATIVE
  - 6-S anomaly: market_pessimism VS business_strength → divergence object
  - 6-Q asked "will this stock go up?" → wrong question
  - 6-S asks "where is the market most likely wrong?" → right question

The MispricingObject is a structured investment thesis, not a score:
  - market_view: what the price implies
  - business_reality: what fundamentals show
  - divergence: the gap between the two
  - thesis: why the market is wrong (generated by doctrine)
  - invalidation: what would prove us wrong
  - confidence: how strong the divergence is

All data uses vintage-aware queries (6-R.0) to prevent look-ahead bias.

Usage:
    from src.thesis.market_anomaly import MarketAnomalyDetector
    detector = MarketAnomalyDetector()
    anomalies = detector.scan(trade_date="2022-04-01")
    # anomalies = [MispricingObject(...), ...]
"""

